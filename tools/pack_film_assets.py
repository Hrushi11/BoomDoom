"""Pack the film art in designs/film-assets/ into one JavaScript data file the stickman engine can load.

    ml/.venv/bin/python tools/pack_film_assets.py

Writes vendor/stickman-skill/engine/data/assets_data.js, which defines `const ASSET_DATA={bg:{...},prop:{...}}`.
Every image is a WebP data URI: a canvas that draws a file:// image is tainted and toDataURL() throws, but data URIs
are not. The file lives in engine/data/ (not engine/*.js or engine/sets/*.js) because the film worker pastes those
into GPT's prompt and the base64 must never go there. Engine code that uses the images is engine/assets.js.

- Backgrounds (bg_*.png, 1024x1536 portrait, opaque) are kept at full size, so the world keeps its margin for camera
  moves; only re-encoded. For the server room, the rack LEDs are located so assets.js can make them blink.
- Props (prop_*.png, 1024x1024 with alpha) are trimmed to their alpha bounding box and downsized to a longest side of
  PROP_MAX. Grip and anchor points in assets.js are fractions of this trimmed box.
"""

from __future__ import annotations

import base64
import io
import json
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "designs" / "film-assets"
OUT = ROOT / "vendor" / "stickman-skill" / "engine" / "data" / "assets_data.js"
PROP_MAX = 512
BG_QUALITY = 90
PROP_QUALITY = 86
ALPHA_TRIM = 8  # alpha at or below this counts as empty when trimming
CELL = 4  # LED clustering grid, image pixels


def webp(im: Image.Image, quality: int) -> str:
    buf = io.BytesIO()
    im.save(buf, "WEBP", quality=quality, method=4)
    return "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()


def leds(im: Image.Image) -> list[list[int]]:
    """Small bright teal or amber lights on the rack fronts (left and right thirds of the picture), as
    [x, y, w, h, colour] boxes in image pixels (colour 0 teal, 1 amber), so assets.js can make them blink."""
    a = np.asarray(im.convert("RGB")).astype(int)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    teal = (g > 150) & (b > 120) & (r < 140) & (g - r > 60)
    amber = (r > 190) & (g > 120) & (b < 110) & (r - b > 110)
    w = r.shape[1]
    side = np.zeros_like(teal)
    side[:, : int(w * 0.3)] = True
    side[:, int(w * 0.7) :] = True
    out = []
    for col, mask in ((0, teal & side), (1, amber & side)):
        cells = {(int(x) // CELL, int(y) // CELL) for y, x in zip(*np.nonzero(mask), strict=True)}
        while cells:  # flood-fill clusters of touching cells
            stack, group = [cells.pop()], []
            while stack:
                c = stack.pop()
                group.append(c)
                for dx in (-1, 0, 1):
                    for dy in (-1, 0, 1):
                        n = (c[0] + dx, c[1] + dy)
                        if n in cells:
                            cells.remove(n)
                            stack.append(n)
            xs = [c[0] for c in group]
            ys = [c[1] for c in group]
            x0, y0 = min(xs) * CELL, min(ys) * CELL
            out.append([x0, y0, (max(xs) + 1) * CELL - x0, (max(ys) + 1) * CELL - y0, col])
    return sorted(out, key=lambda q: (q[1], q[0]))


def main() -> None:
    data: dict = {"bg": {}, "prop": {}}
    for f in sorted(SRC.glob("bg_*.png")):
        im = Image.open(f).convert("RGB")
        entry = {"w": im.width, "h": im.height, "src": webp(im, BG_QUALITY)}
        if f.stem == "bg_server_room":
            entry["leds"] = leds(im)
        data["bg"][f.stem[3:]] = entry
    for f in sorted(SRC.glob("prop_*.png")):
        im = Image.open(f).convert("RGBA")
        box = im.getchannel("A").point(lambda v: 255 if v > ALPHA_TRIM else 0).getbbox()
        im = im.crop(box)
        im.thumbnail((PROP_MAX, PROP_MAX), Image.LANCZOS)
        data["prop"][f.stem[5:]] = {"w": im.width, "h": im.height, "src": webp(im, PROP_QUALITY)}
    OUT.parent.mkdir(parents=True, exist_ok=True)
    body = json.dumps(data, separators=(",", ":"))
    OUT.write_text(
        "// GENERATED by tools/pack_film_assets.py from designs/film-assets/. Do not edit. Images as WebP data URIs.\n"
        f"const ASSET_DATA={body};\n"
    )
    size = OUT.stat().st_size
    print(f"wrote {OUT} ({size / 1e6:.2f} MB): {len(data['bg'])} backgrounds, {len(data['prop'])} props")
    for kind in ("bg", "prop"):
        tot = sum(len(v["src"]) for v in data[kind].values())
        print(f"  {kind}: {tot / 1e6:.2f} MB base64")
    print(f"  server-room LEDs: {len(data['bg'].get('server_room', {}).get('leds', []))}")


if __name__ == "__main__":
    main()
