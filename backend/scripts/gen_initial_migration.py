"""Regenerate alembic/versions/0001_initial.py from app.models (offline, PostgreSQL dialect).

Only for the initial schema before first deploy. After that, use `alembic revision --autogenerate`.
"""

from pathlib import Path

from sqlalchemy.dialects import postgresql
from sqlalchemy.schema import CreateIndex, CreateTable

from app import models  # noqa: F401
from app.db import Base

d = postgresql.dialect()
up = []
for t in Base.metadata.sorted_tables:
    up.append(str(CreateTable(t).compile(dialect=d)).strip())
    up.extend(str(CreateIndex(ix).compile(dialect=d)).strip() for ix in sorted(t.indexes, key=lambda i: i.name or ""))
down = [f"DROP TABLE IF EXISTS {t.name} CASCADE" for t in reversed(Base.metadata.sorted_tables)]

body = f'''"""initial schema (Tech Spec §8.4 + scaffold additions)

Generated by scripts/gen_initial_migration.py. For later changes use `alembic revision --autogenerate`.

Revision ID: 0001
Revises:
"""

from alembic import op

revision = "0001"
down_revision = None
branch_labels = None
depends_on = None

UPGRADE = {up!r}

DOWNGRADE = {down!r}


def upgrade() -> None:
    for stmt in UPGRADE:
        op.execute(stmt)


def downgrade() -> None:
    for stmt in DOWNGRADE:
        op.execute(stmt)
'''
Path("alembic/versions/0001_initial.py").write_text(body)
print(f"{len(up)} statements")
